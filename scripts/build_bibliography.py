"""Generate both manuscript references and reusable BibTeX from verified metadata."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re


def tex(value: str) -> str:
    mapping = {"&": r"\&", "%": r"\%", "_": r"\_", "#": r"\#", "Ś": r"\'{S}", "ü": r'\"{u}'}
    return "".join(mapping.get(c, c) for c in value)


def build(source: Path, output: Path) -> dict:
    payload = json.loads(source.read_text(encoding="utf-8"))
    records = payload["records"]
    keys = [r["key"] for r in records]
    if len(set(keys)) != len(keys) or any(not re.fullmatch(r"[a-zA-Z0-9_-]+", k) for k in keys):
        raise ValueError("Bibliography keys must be unique and safe")
    output.mkdir(parents=True, exist_ok=True)
    lines = ["% Generated by scripts/build_bibliography.py; edit verified JSON, not this file.", r"\begingroup\small\raggedright", r"\begin{thebibliography}{99}"]
    bib = ["% Generated from docs/publication/bibliography.json.\n"]
    for r in records:
        authors = ", ".join(r["authors"][:-1]) + (" and " if len(r["authors"]) > 1 else "") + r["authors"][-1]
        author_label = r["authors"][0].split()[-1] + (" et al." if len(r["authors"]) > 2 else " and " + r["authors"][1].split()[-1] if len(r["authors"]) == 2 else "")
        locator = r.get("volume", "") + ("(" + r["issue"] + ")" if r.get("issue") else "")
        if r.get("pages"):
            locator += ":" + r["pages"]
        if r.get("eprint"):
            locator = "arXiv:" + r["eprint"]
        lines += [f"\\bibitem[{tex(author_label)}({r['year']})]{{{r['key']}}}",
                  f"{tex(authors)} ({r['year']}). {tex(r['title'])}. \\emph{{{tex(r['venue'])}}}" + (", " + tex(locator) if locator else "") + ".",
                  "\\href{" + r["url"] + "}{" + ("doi:" + r["doi"] if r.get("doi") else "Source and version") + "}."]
        if r.get("print_note"):
            lines.append(tex(r["print_note"]))
        entry = {"author": " and ".join(r["authors"]), "title": "{" + r["title"] + "}", "year": str(r["year"]),
                 **{k: r[k] for k in ("volume", "issue", "pages", "doi", "url", "eprint") if k in r}}
        kind = r.get("entry_type", "article" if r.get("doi") and not r["doi"].startswith("10.2139/") else "misc")
        if kind not in ("article", "inproceedings", "misc"):
            raise ValueError("Unsupported bibliography entry type")
        entry[{"article":"journal", "inproceedings":"booktitle", "misc":"howpublished"}[kind]] = r["venue"]
        if r.get("print_note"):
            entry["note"] = r["print_note"]
        if "issue" in entry:
            entry["number"] = entry.pop("issue")
        bib.append("@" + kind + "{" + r["key"] + ",\n" + ",\n".join("  " + k + " = {" + tex(v) + "}" for k, v in entry.items()) + "\n}\n")
    lines.append(r"\end{thebibliography}")
    lines.append(r"\endgroup")
    (output / "references.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (output / "references.bib").write_text("\n".join(bib), encoding="utf-8")
    record = {"source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(), "records": len(keys), "keys": keys,
              "output_sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in (output / "references.tex", output / "references.bib")}}
    (output / "bibliography-manifest.json").write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    return record


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("docs/publication/bibliography.json"))
    parser.add_argument("--output", type=Path, default=Path("paper"))
    args = parser.parse_args()
    print(json.dumps(build(args.source, args.output), indent=2))
